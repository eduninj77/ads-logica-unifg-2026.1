# Complete as frases com os termos adequados: **linha**, **coluna**, **lista externa**, **lista interna**, **elemento**.

#1. Em uma matriz, cada sublista pode ser interpretada como uma lista interna.
#2. A estrutura que agrupa todas as sublistas é chamada de lista externa.
#3. O valor armazenado em uma posição específica é chamado de elemento.
#4. Em `matriz[2][0]`, o índice `2` seleciona a linha.
#5. Em `matriz[2][0]`, o índice `0` seleciona a coluna dentro da linha.