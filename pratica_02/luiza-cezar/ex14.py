# Versão equivalente usando for para um loop com início, fim e passo definidos
for i in range(1, 11):
    print(i)

# A versão com for pode ser mais legível quando já se conhece o número de
# repetições e o contador segue um padrão simples, pois o controle do loop
# fica embutido na própria estrutura.
# O while ainda é mais adequado quando a repetição depende de uma condição
# que não tem um limite fixo conhecido antecipadamente, como aguardar uma
# entrada do usuário até que ela seja válida.
